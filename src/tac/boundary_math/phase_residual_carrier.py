"""PHASE-RESIDUAL CARRIER — the STORE half of the appearance-phase d_seg reframe.

BACKGROUND (`.omx/research/flicker_transform_geometry_term_design_20260710.md`, DAG
FEED-flicker-term, MEMORY L85): the witness converges to the temporal-majority oracle floor
(``d_seg ≈ 0.005318`` = the GT stride-2 spike rate); sub-0.15 needs d_seg 0.0008–0.0012, which is
4.5–7× BELOW that flicker floor. The floor is pierceable ONLY by APPEARANCE-PHASE faithfulness:
the per-pair spikes are DETERMINISTIC functions of the boundary's sub-pixel phase and are per-pair
SEPARABLE in the objective (``evaluate.py:96`` — the score is a SUM of independent per-pair terms).
The train/store SPLIT:

  * TRAIN-side (T1 / #360 phase-advection lever): the witness descends the ξ-COHERENT part of the
    phase — the fraction generated by the ego-screw transport A_ξ (nearly free, amortized).
  * STORE-side (THIS module): the phase-carrier STORES the per-pair RESIDUAL the witness CANNOT
    predict — ``r = t_wit_actual − t_wit_ξ_predicted`` — entropy-coded, byte-closed into the L13
    task-space format. Most of the phase is captured by ξ-transport; only the small residual is
    COUNTED. A per-pair channel, but ξ-AMORTIZED.

THE PRIMITIVE (the store-what-doesn't-generalize half):
  * ``t_wit`` = the sub-pixel TIE COORDINATE of the φ=0 boundary at a straddle pixel
    (``Mw[p]/(Mw[p]+Mw[q])``) — the SAME quantity T1 / Force-3 compute. Imported from
    :mod:`tac.boundary_math.phase_primitives` (NO duplication — ONE tie coordinate in the repo).
  * ``t_wit_ξ_predicted`` = the ξ-transport ``A_ξ`` of the PREVIOUS scored frame's tie field
    (:func:`tac.boundary_math.phase_primitives.advect_tie_field_numpy`) — the SAME warp Force-1
    uses. The dual-use pose ξ (#140 / R1 stored twist) IS the phase's ξ; NO separate ξ is stored.
  * cross-scored-frame gap screw = :func:`phase_primitives.cross_scored_frame_xi_interp`.

CODEC (encode; deterministic, $0, numpy+stdlib):
  1. per SCORED frame p (=f1 of pair p) compute the actual tie field ``t[p]`` on the active
     straddle annulus, partitioned per GROUND class {Road=0, Lane=1, Undrivable=2}.
  2. CLOSED-LOOP predictor: ``t_pred[p] = A_ξ(t_dec[p-1])`` (advect the DECODED previous-frame full
     tie field by the cross-frame screw). ``p==0`` predicts a constant ``anchor_predict`` (no prior).
  3. residual ``r[p] = round((t[p] − t_pred[p]) / q_step)`` (int64) on the active pixels only.
  4. reconstruct ``t_dec[p] = clip(t_pred[p] + r[p]·q_step, 0, 1)`` — encoder predicts from the SAME
     values the decoder will see (no drift), exactly as ``xi_spline_residual_coder`` does.
  5. ONE integer residual stream across frames × classes → the SHARED entropy stage
     (:func:`tac.boundary_math.xi_spline_residual_coder.encode_residual_matrix`; best-of
     {varint, zlib9, rice}, self-describing id). ONE residual entropy stage in the repo.
  6. NO-FAKE self-check: encode runs the FULL decode and REFUSES (raises) unless the reconstructed
     tie fields are BIT-IDENTICAL to the closed-loop quantized reconstruction.

RULE-118 boundary (the store-what-doesn't-generalize / free-generic split):
  * COUNTED (archive.zip): the quantized per-pair phase RESIDUAL (video-derived; the part ξ-transport
    cannot predict).
  * FREE (inflate.py): the ξ-transport warp A_ξ + the tie-coordinate extraction (generic algorithm),
    and the ACTIVE STRADDLE MASK + class map are DECODER-DERIVABLE (the witness's own rendered
    partition) — never stored. Only the residual VALUES are counted; the boundary GEOMETRY is free.

DETERMINISM: numpy-fp64 CPU is the authority (same class as the shipped ξ carrier). The MLX tie
extraction (:func:`compute_tie_field_from_margins_mlx`) is a differentiable twin used to source the
train-side quantity; the codec encode/decode are numpy+stdlib ONLY so inflate stays numpy-portable.
The encoder's bit-identity self-check makes any host fp divergence FAIL CLOSED. NEVER a score
authority — this module produces BYTES; the d_seg it recovers is measured through the frozen CPU
scorer on the exact byte-closed decode, and the pointer (0.19108) moves only via
``upstream/evaluate.py``. MPS is NEVER an authority.

Default-OFF: absent a phase-carrier section the byte-close blob is BYTE-IDENTICAL to the pre-phase
grammar (the 7th optional block is manifest-gated, like the #205 pose carrier's 6th block).
"""
