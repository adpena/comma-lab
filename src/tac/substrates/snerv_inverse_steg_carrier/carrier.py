"""SNeRV-inspired carrier — store LF coefficients, GENERATE HF detail.

The SNeRV (Spectra-preserving NeRV, arXiv 2501.01681) carrier represents a frame as a
multi-level orthonormal 2D wavelet pyramid and:

  * **STORES** only the coarsest LF (LL approximation) subband — ~``H*W / 4^L``
    coefficients at level ``L``, quantized to a small bit budget. This is the
    dominant archive content but is itself tiny (a 384x512 frame at level 3 has
    only 48x64 = 3072 LF coefficients per channel).
  * **GENERATES** the HF detail subbands with a small per-level decoder. The
    decoder is a learned linear upsampling map (one small kernel per level) whose
    weights ARE in the archive but are byte-cheap (shared across all frames).

This is the **super-small-rate-by-design** carrier the operator asked for: the
byte-heavy detail is generated, not stored (curing the Z8 disease where the raw
wavelet detail blob was ~99.5% of the archive). Distortion is "solved" because
the LF approximation already captures the low-frequency structure SegNet's
stride-2 stem actually sees, and the L-inf pose-Fisher allocation (``allocation.py``)
spends the LF bit budget exactly where the detector is sensitive.

Decoder generation model (contest adapter, not upstream bit-exact parity): at
each pyramid level the HF detail tuple ``(LH, HL, HH)`` is GENERATED from the
current approximation ``LL`` via learned receiver-visible predictors per
subband. The default historical predictor is a 3x3 local LF patch. The
``snerv_spectra_preserving_mfu_hfr_temporal_adapter_v1`` predictor uses a
receiver-safe version of the paper's core stack: multi-resolution fusion (MFU),
high-frequency restoration (HFR), and an explicit temporal LF-delta utility
(SNeRV_T). This is still marked as a local spectra-preserving adapter until
full upstream OSS parity is proven, but it is executable, byte-priced, and
decoded by the contest runtime without hidden sidecars.

[verified-local: DWT adjoint exactness in ``dwt.py`` and deterministic receiver
roundtrip surfaces. Source-faithful SNeRV parity remains blocked until the
official OSS/paper gates pass.]

Catalog #290 (canonical-vs-unique): the DWT is ADOPTED canonical (``dwt.py`` uses
pywt). The HF-generation decoder is FORK_PRINCIPLED — SNeRV's distinguishing
feature is the generate-HF-from-LF map, which no existing substrate provides; it
must be unique to this carrier. The score-aware loss ADOPTS the canonical
bit-exact mirror (``load_score_exact_scorers``) because measurement authority must
be canonical.
"""

